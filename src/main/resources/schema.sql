CREATE TABLE IF NOT EXISTS credit_code_counters (
    counter_date DATE NOT NULL,
    counter_key VARCHAR(40) NOT NULL,
    last_value INTEGER NOT NULL CHECK (last_value BETWEEN 1 AND 999999),
    PRIMARY KEY (counter_date, counter_key)
);

CREATE TABLE IF NOT EXISTS credits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_number VARCHAR(40) NOT NULL UNIQUE,
    customer_number BIGINT NOT NULL CHECK (customer_number > 0),
    credit_type VARCHAR(20) NOT NULL CHECK (credit_type IN ('PERSONAL', 'BUSINESS')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'PAID', 'CLOSED')),
    original_amount NUMERIC(19, 2) NOT NULL CHECK (original_amount > 0),
    outstanding_debt NUMERIC(19, 2) NOT NULL CHECK (
        outstanding_debt >= 0 AND outstanding_debt <= original_amount
    ),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'PEN'),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_credits_customer_number ON credits(customer_number);
CREATE UNIQUE INDEX IF NOT EXISTS uq_credits_active_personal_customer
    ON credits(customer_number)
    WHERE credit_type = 'PERSONAL' AND status = 'ACTIVE';

CREATE TABLE IF NOT EXISTS credit_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_code VARCHAR(60) NOT NULL UNIQUE,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    credit_id BIGINT NOT NULL REFERENCES credits(id),
    movement_type VARCHAR(20) NOT NULL CHECK (movement_type IN ('DISBURSEMENT', 'PAYMENT')),
    amount NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    debt_after NUMERIC(19, 2) NOT NULL CHECK (debt_after >= 0),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'PEN'),
    payment_source VARCHAR(20) CHECK (payment_source IS NULL OR payment_source = 'EXTERNAL'),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (
        (movement_type = 'DISBURSEMENT' AND payment_source IS NULL)
        OR (movement_type = 'PAYMENT' AND payment_source IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_credit_movements_credit_occurred
    ON credit_movements(credit_id, occurred_at, id);
